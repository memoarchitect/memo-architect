import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const toolsRoot = dirname(require.resolve('@memoarchitect/tools/package.json'));
const bnf = readFileSync(join(toolsRoot, 'corpus/sysml-v2-release/bnf/SysML-graphical-bnf.kgbnf'), 'utf8');
const productions = ['accept-action-node', 'send-action-node', 'decision-node', 'merge-node', 'fork-node', 'join-node'];
for (const production of productions) {
    if (!bnf.includes(`${production} =`)) throw new Error(`Graphical BNF does not define ${production}.`);
}
const output = `// Generated by scripts/generate-notation-registry.mjs from SysML-graphical-bnf.kgbnf. Do not edit.\nexport const GRAPHICAL_BNF_SOURCE = 'SysML-graphical-bnf.kgbnf' as const;\nexport const GRAPHICAL_BNF_PRODUCTIONS = ${JSON.stringify(productions, null, 4)} as const;\n`;
writeFileSync(new URL('../packages/web/src/diagram/notation-bnf.generated.ts', import.meta.url), output);
