#!/usr/bin/env node

import { Command } from 'commander';
import { architectBuildCommand } from '../commands/build.js';
import { ConfigSettingError, configGetCommand, configSetCommand, configUnsetCommand } from '../commands/config.js';
import { architectDevCommand } from '../commands/dev.js';
import {
    architectExampleCommand, listArchitectExamples,
} from '../commands/example.js';
import { EXPERIMENTAL_FLAG_DESCRIPTION, resolveFeatureGrants } from '../feature-grants.js';
import {
    applyToolchainCliOptions, defaultRegistry, ProjectNamesUserSettingError, registerProjectCommands, toolchainOptionName, ToolchainNotConfiguredError,
} from '@memoarchitect/tools';

const program = new Command();

/**
 * Toolchain flags, generated by MEMO Tools from its provider registry.
 *
 * Architect declares none of them itself and reads none of their values: it
 * forwards them to the operation that owns the toolchain. That is the whole of
 * §1.2.2 here — anything you can do in the UI you can script, without Architect
 * learning a provider's name or a tool's output format.
 */
const TOOLCHAIN_OPTION_NAMES = defaultRegistry.schema().map(toolchainOptionName);

function toolchainOptionsFrom(options: Record<string, unknown>): Record<string, unknown> {
    return Object.fromEntries(
        TOOLCHAIN_OPTION_NAMES
            .filter(name => options[name] !== undefined)
            .map(name => [name, options[name]]),
    );
}

program
    .name('memo-architect')
    .description('MEMO Architect — interactive and distributable model workbench')
    .version('0.6.6')
    .option('--example <name>', 'Open a bundled example project (e.g. gpca, standard-sysml-diagrams). A local checkout is opened in place; an installed package is opened read-only in a disposable copy')
    .option('--read-only', 'Always open the example in a disposable copy, even from a local checkout')
    .option('-p, --port <port>', 'Server port', '3000')
    .option('--no-open', 'Do not open a browser')
    .option('--keep-alive', 'Keep running after the last browser disconnects')
    .option('--experimental', EXPERIMENTAL_FLAG_DESCRIPTION)
    .action(async (options: {
        example?: string; port: string; open: boolean; readOnly?: boolean; experimental?: boolean; keepAlive?: boolean;
    }) => {
        if (options.example) {
            await architectExampleCommand({
                name: options.example,
                port: Number.parseInt(options.port, 10),
                open: options.open,
                readOnly: options.readOnly,
                featureGrants: resolveFeatureGrants(options),
                keepAlive: options.keepAlive,
            });
            return;
        }
        program.help();
    });

/**
 * Read an option that is declared on both this command and its parent.
 *
 * `-p, --port` and `--no-open` exist on the program so `--example` can take
 * them, and on `dev` so it can too. Commander binds the flag on the command
 * line to the program-level declaration, leaving the subcommand holding its
 * own default — which silently pinned `dev --port` to 3000. Prefer whichever
 * declaration the user actually set, falling back to the local default.
 */
function resolveOption<T>(command: Command, name: string, local: T): T {
    if (command.getOptionValueSource(name) === 'cli') return local;
    const parent = command.parent;
    if (parent?.getOptionValueSource(name) === 'cli') return parent.opts()[name] as T;
    return local;
}

applyToolchainCliOptions(
    program
        .command('dev')
        .description('Start Architect with live model reload')
        .option('-p, --port <port>', 'Server port', '3000')
        .option('--no-open', 'Do not open a browser')
.option('--keep-alive', 'Keep running after the last browser disconnects')
.option('--experimental', EXPERIMENTAL_FLAG_DESCRIPTION),
defaultRegistry,
).action(async function (this: Command, options: Record<string, unknown>) {
    const port = resolveOption(this, 'port', options.port as string);
    const open = resolveOption(this, 'open', options.open as boolean);
    const experimental = resolveOption(this, 'experimental', options.experimental as boolean | undefined);
    const keepAlive = resolveOption(this, 'keepAlive', options.keepAlive as boolean | undefined);
    // Exactly what the caller passed. The compiler is the project's setting;
    // Architect chooses none for a project that does not.
    const toolchainOptions = toolchainOptionsFrom(options);
    await architectDevCommand({
        port: Number.parseInt(String(port), 10),
        open,
        featureGrants: resolveFeatureGrants({ experimental }),
        keepAlive: keepAlive === true,
        toolchainOptions,
        toolchainArgv: Object.entries(toolchainOptions)
            .flatMap(([name, value]) => [`--${name}`, String(value)]),
    });
});

// ─── The project commands, and settings ────────────────────────────────────
// MEMO Tools' program compiles and validates; everything else a person does with a
// project (create it, author, package, export, the AI helpers, the regulatory
// workbench) is registered from MEMO Tools' implementations here. Choosing the
// compiler is Architect's own.
registerProjectCommands(program);

const configCommand = program
    .command('config')
    .description('Settings: choose the compiler, for yourself or with --project for everyone on the project (what is in effect: memo compile --effective)');

configCommand
    .command('set')
    .description('Set a setting for yourself (overrides the project\'s), or with --project for the whole project')
    .argument('<setting>', 'compiler. (Low-level overrides such as opensysml.binary or syside.python exist for unusual installs; MEMO finds tools in the usual places.)')
    .argument('<value>', 'the value')
    .option('--project', 'Write the project\'s checked-in settings file instead of your own')
    .action((setting: string, value: string, options: { project?: boolean }) => {
        configSetCommand(setting, value, options.project ? { root: process.cwd() } : undefined);
    });

configCommand
    .command('get')
    .description('Show your settings and which layer decided each: the command line, the environment, yours, the project\'s')
    .argument('[setting]', 'One setting; the compiler when omitted')
    .option('--all', 'Also list the low-level overrides (where a tool is, the validator and lowering roles)')
    .action((setting: string | undefined, options: { all?: boolean }) => { configGetCommand(setting, options); });

configCommand
    .command('unset')
    .description('Remove a setting of your own, or with --project the project\'s')
    .argument('<setting>', 'the setting')
    .option('--project', 'Remove it from the project\'s checked-in settings file instead of your own')
    .action((setting: string, options: { project?: boolean }) => {
        configUnsetCommand(setting, options.project ? { root: process.cwd() } : undefined);
    });

program
    .command('examples')
    .description('List bundled example IDs accepted by --example')
    .action(() => {
        console.log('Available examples:');
        for (const id of listArchitectExamples()) console.log(`  ${id}`);
        console.log('\nOpen one with: memo-architect --example <id>');
    });

program
    .command('build')
    .description('Build a static Architect viewer with embedded project data')
    .option('-o, --output <dir>', 'Output directory', 'dist')
    .option('--standalone', 'Inline the entry JavaScript and CSS into index.html')
    .option('--experimental', EXPERIMENTAL_FLAG_DESCRIPTION)
    .action(async function (this: Command, options: { output: string; standalone?: boolean; experimental?: boolean }) {
        // `--experimental` is declared on the program too, so Commander binds a
        // command-line flag to the parent and leaves this command holding its
        // own default. Same trap as `--port` on `dev`.
        const experimental = resolveOption(this, 'experimental', options.experimental);
        await architectBuildCommand({
            ...options,
            featureGrants: resolveFeatureGrants({ experimental }),
        });
    });

// A project whose settings name no compiler is told what to set, not shown a
// stack: Architect chooses none for it. Anything else is still a crash.
program.parseAsync().catch((error: unknown) => {
    if (error instanceof ToolchainNotConfiguredError || error instanceof ProjectNamesUserSettingError || error instanceof ConfigSettingError) {
        console.error(`\n❌ ${error.message}\n`);
        process.exit(1);
    }
    throw error;
});
